"""Environment-derived settings for test harness utilities."""

from __future__ import annotations

import os

from src.runtime.settings import read_settings
from config.tests.defaults import (
    GENDER_DEFAULT,
    SERVER_URL_DEFAULT,
    PERSONALITY_DEFAULT,
    IDLE_WAIT_SECONDS_DEFAULT,
    IDLE_GRACE_SECONDS_DEFAULT,
    IDLE_EXPECT_SECONDS_DEFAULT,
    PING_TIMEOUT_SECONDS_DEFAULT,
    PING_INTERVAL_SECONDS_DEFAULT,
)
from tests.harness.environment.variables import read_environment_float, read_environment_integer

DEFAULT_APPLICATION_SETTINGS = read_settings(environment={})

DEFAULT_SERVER_URL = os.getenv("SERVER_URL", SERVER_URL_DEFAULT)
DEFAULT_GENDER = os.getenv("GENDER", GENDER_DEFAULT)
DEFAULT_PERSONALITY = os.getenv("PERSONALITY", PERSONALITY_DEFAULT)
DEFAULT_PING_INTERVAL_SECONDS = read_environment_integer(
    "TEST_WEBSOCKET_PING_INTERVAL_SECONDS",
    PING_INTERVAL_SECONDS_DEFAULT,
)
DEFAULT_PING_TIMEOUT_SECONDS = read_environment_integer(
    "TEST_WEBSOCKET_PING_TIMEOUT_SECONDS",
    PING_TIMEOUT_SECONDS_DEFAULT,
)

_WEBSOCKET_IDLE_TIMEOUT_TEXT = os.getenv("WEBSOCKET_IDLE_TIMEOUT_SECONDS")
_IDLE_EXPECT_SECONDS_DEFAULT = (
    float(_WEBSOCKET_IDLE_TIMEOUT_TEXT)
    if _WEBSOCKET_IDLE_TIMEOUT_TEXT is not None and _WEBSOCKET_IDLE_TIMEOUT_TEXT.strip()
    else IDLE_EXPECT_SECONDS_DEFAULT
)

IDLE_NORMAL_WAIT_SECONDS = read_environment_float("IDLE_NORMAL_WAIT_SECONDS", IDLE_WAIT_SECONDS_DEFAULT)
IDLE_EXPECT_SECONDS = read_environment_float("IDLE_EXPECT_SECONDS", _IDLE_EXPECT_SECONDS_DEFAULT)
IDLE_GRACE_SECONDS = read_environment_float("IDLE_GRACE_SECONDS", IDLE_GRACE_SECONDS_DEFAULT)

__all__ = [
    "DEFAULT_APPLICATION_SETTINGS",
    "DEFAULT_GENDER",
    "DEFAULT_PERSONALITY",
    "DEFAULT_PING_INTERVAL_SECONDS",
    "DEFAULT_PING_TIMEOUT_SECONDS",
    "DEFAULT_SERVER_URL",
    "IDLE_EXPECT_SECONDS",
    "IDLE_GRACE_SECONDS",
    "IDLE_NORMAL_WAIT_SECONDS",
]
